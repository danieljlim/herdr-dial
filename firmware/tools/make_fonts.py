"""Regenerate the dial's LVGL fonts from IBM Plex Mono (bundled in firmware/fonts/).

    python firmware/tools/make_fonts.py

The output, firmware/src/fonts/, is checked in, so this only needs running after changing the sizes
or glyphs below. Without that folder the firmware falls back to LVGL's built-in Montserrat.

Needs Node.js (it runs lv_font_conv through npx).
"""

import os
import re
import shutil
import subprocess
import sys

FIRMWARE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(FIRMWARE, "fonts")
OUT_DIR = os.path.join(FIRMWARE, "src", "fonts")
LV_FONT_CONV = "lv_font_conv@1.5.2"

# Printable ASCII (the bridge sends ASCII-only names) plus the middle dot used in the summary.
GLYPHS = "0x20-0x7E,0xB7"

# role: (font file, pixel size). Roles are what ui.cpp asks for.
ROLES = {
    "status": ("IBMPlexMono-SemiBold.ttf", 30),
    "name": ("IBMPlexMono-Regular.ttf", 20),
    "small": ("IBMPlexMono-Regular.ttf", 15),
    "mono": ("IBMPlexMono-Regular.ttf", 15),
}
# The status bar's battery / USB / Bluetooth icons only exist in LVGL's Montserrat.
FALLBACK = {"mono": "lv_font_montserrat_14"}


def convert(role, path, size):
    symbol = f"speeddial_font_{role}"
    out = os.path.join(OUT_DIR, f"{symbol}.c")
    npx = shutil.which("npx") or sys.exit("needs Node.js: npx not found")
    subprocess.run([npx, "-y", LV_FONT_CONV, "--font", path, "-r", GLYPHS, "--size", str(size),
                    "--bpp", "4", "--format", "lvgl", "--no-compress", "-o", out], check=True)

    with open(out, encoding="utf-8") as f:
        source = f.read()
    # Keep the conversion options out of the file: they contain local paths.
    source = re.sub(r" \* Opts: .*\n", "", source)
    if role in FALLBACK:
        source = source.replace("/*-----------------\n *  PUBLIC FONT",
                                f"LV_FONT_DECLARE({FALLBACK[role]});\n\n/*-----------------\n *  PUBLIC FONT", 1)
        source = re.sub(r"(\.dsc = &font_dsc)", rf"\1,\n    .fallback = &{FALLBACK[role]}", source, count=1)
    with open(out, "w", encoding="utf-8") as f:
        f.write(source)
    return symbol


def main():
    shutil.rmtree(OUT_DIR, ignore_errors=True)
    os.makedirs(OUT_DIR)
    lines = ["// Generated by firmware/tools/make_fonts.py.", "#pragma once", "", '#include "lvgl.h"', ""]
    for role, (name, size) in ROLES.items():
        symbol = convert(role, os.path.join(FONT_DIR, name), size)
        lines.append(f"LV_FONT_DECLARE({symbol});  // {name}, {size}px")
        lines.append(f"#define FONT_{role.upper()} (&{symbol})")
        print(f"{role}: {name} {size}px")
    with open(os.path.join(OUT_DIR, "speeddial_fonts.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
